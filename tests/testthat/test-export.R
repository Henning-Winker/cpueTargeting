fit_two <- function(seed = 1) {
  sim <- simulate_logbook(seed = seed, plots = FALSE)
  x <- cpue_data(sim$logbook, year = "year", species = "species", catch = "kg",
                 id = "trip", vessel = "vessel")
  x <- add_targeting(select_species(x, keep = "Pagellus bogaraveo"))
  fit_cpue(x, "Pagellus bogaraveo", models = c("Base", "Cluster"))
}

test_that("index_set() harmonises fits, lists and data frames", {
  f <- fit_two()
  s1 <- index_set(f)
  expect_s3_class(s1, "cpue_index_set")
  expect_equal(unique(s1$name), "Cluster")
  expect_equal(s1$index, f$indices$index[f$indices$model == "Cluster"])
  s2 <- index_set(f, model = c("Base", "Cluster"), normalise = TRUE)
  expect_equal(unique(s2$name), c("Base", "Cluster"))
  expect_equal(as.numeric(tapply(s2$index, s2$name, mean)), c(1, 1))
  expect_equal(s2$se_log, f$indices$se_log[match(paste(s2$name, s2$year),
                                                 paste(f$indices$model, f$indices$year))])
  s3 <- index_set(list(a = f, b = f), model = "Base", years = 2005:2010)
  expect_equal(unique(s3$name), c("a", "b"))
  expect_true(all(s3$year %in% 2005:2010))
  s4 <- index_set(list(a = f, b = f), model = c("Base", "Cluster"))
  expect_equal(unique(s4$name), c("a_Base", "a_Cluster", "b_Base", "b_Cluster"))
  df <- data.frame(year = 2001:2003, index = c(1, 2, NA), se_log = 0.2)
  expect_equal(nrow(index_set(df)), 2)
  expect_error(index_set(f, model = "DPC"), "not in the fit")
  expect_error(index_set(list(f, f)), "must be named")
  expect_error(index_set(rbind(df, df)), "Duplicated")
})

test_that("as_jabba() returns JABBA cpue and se tables", {
  f <- fit_two()
  jb <- as_jabba(list(a = f, b = f), model = "Cluster", years = 2003:2020)
  expect_named(jb, c("cpue", "se"))
  expect_equal(names(jb$cpue), c("year", "a", "b"))
  expect_equal(names(jb$se), names(jb$cpue))
  expect_equal(jb$cpue$year, 2003:2020)
  s <- index_set(f, model = "Cluster", years = 2003:2020)
  expect_equal(jb$cpue$a, s$index)
  expect_equal(jb$se$b, s$se_log)
  # unequal years give NA
  df <- list(x = data.frame(year = 2001:2004, index = 1:4, se_log = 0.1),
             y = data.frame(year = 2003:2006, index = 1:4, se_log = 0.2))
  jb2 <- as_jabba(df)
  expect_equal(jb2$cpue$year, 2001:2006)
  expect_equal(sum(is.na(jb2$cpue$x)), 2)
  expect_equal(sum(is.na(jb2$se$y)), 2)
})

test_that("as_spict() returns obsI, timeI, stdevfacI and a logsdi prior", {
  f <- fit_two()
  si <- as_spict(f, model = c("Base", "Cluster"), timing = c(0, 0.5), sdi_sd = 0.3)
  expect_named(si, c("obsI", "timeI", "stdevfacI", "priors", "sdI"))
  expect_length(si$obsI, 2)
  s <- index_set(f, model = c("Base", "Cluster"))
  expect_equal(si$obsI$Cluster, s$index[s$name == "Cluster"])
  expect_equal(si$timeI$Base, s$year[s$name == "Base"])
  expect_equal(si$timeI$Cluster, s$year[s$name == "Cluster"] + 0.5)
  expect_equal(si$stdevfacI$Cluster * si$sdI[["Cluster"]], s$se_log[s$name == "Cluster"])
  expect_equal(mean(si$stdevfacI$Base), 1)
  expect_true(is.list(si$priors$logsdi))
  expect_equal(si$priors$logsdi[[2]], c(log(si$sdI[["Cluster"]]), 0.3, 1))
  one <- as_spict(f)
  expect_true(is.numeric(one$priors$logsdi))
  expect_length(one$priors$logsdi, 3)
  expect_length(as_spict(f, sdi_sd = NA)$priors, 0)
})

test_that("as_FLIndexBiomass() and as_FLIndices() follow the JABBA3 convention", {
  skip_if_not_installed("FLCore")
  f <- fit_two()
  fi <- as_FLIndexBiomass(f, model = "Cluster", startf = 0, endf = 2 / 12, units = "kg/trip")
  expect_s4_class(fi, "FLIndexBiomass")
  s <- index_set(f, model = "Cluster")
  expect_equal(as.numeric(FLCore::index(fi)), s$index)
  expect_equal(as.numeric(FLCore::index.var(fi)), s$se_log)
  expect_equal(as.numeric(dimnames(FLCore::index(fi))$year), s$year)
  expect_equal(unname(fi@range[c("startf", "endf")]), c(0, 2 / 12))
  expect_equal(FLCore::name(fi), "Cluster")
  expect_error(as_FLIndexBiomass(f, model = c("Base", "Cluster")), "as_FLIndices")
  fl <- as_FLIndices(list(jf = f, winter = f), model = "Cluster",
                     years = c(2001:2005, 2008:2012))
  expect_s4_class(fl, "FLIndices")
  expect_equal(names(fl), c("jf", "winter"))
  # gaps are filled with NA in a continuous year range
  expect_equal(sum(is.na(as.numeric(FLCore::index(fl[["jf"]])))), 2)
})

test_that("FLIndices are read back by JABBA3 as the JABBA tables", {
  skip_if_not_installed("FLCore")
  skip_if_not_installed("JABBA3")
  f <- fit_two()
  fl <- as_FLIndices(f, model = c("Base", "Cluster"))
  jb <- as_jabba(f, model = c("Base", "Cluster"))
  back <- JABBA3::flr2jbdat(FLCore::FLQuant(1, dimnames = list(age = "all", year = jb$cpue$year)), fl)
  expect_equal(unname(as.matrix(back$cpue[, -1])), unname(as.matrix(jb$cpue[, -1])))
  expect_equal(unname(as.matrix(back$se[, -1])), unname(as.matrix(jb$se[, -1])))
})
